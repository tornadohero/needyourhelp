/**
 * Domain view of the conversation aggregate
 * (`specs/04-database-spec.md` §conversations, §conversation_members,
 * §message_refs; `specs/09-im-spec.md`).
 *
 * The transport is the IM adapter's; the platform keeps the membership, the
 * lifecycle status and, only if the selected design requires it, references to
 * messages. Message content is never persisted here.
 */

export type ConversationStatus = 'OPEN' | 'BLOCKED' | 'CLOSED';

export type ConversationMemberRole = 'BUYER' | 'PROVIDER' | 'SYSTEM';

export type MessageType = 'TEXT' | 'IMAGE' | 'SYSTEM';

export type MessageModerationStatus = 'PENDING' | 'APPROVED' | 'REJECTED';

export interface ConversationMember {
  userId: string;
  role: ConversationMemberRole;
}

export interface MessageReference {
  id: string;
  conversationId: string;
  externalMessageId: string;
  senderUserId: string;
  messageType: MessageType;
  moderationStatus: MessageModerationStatus;
  createdAt: Date;
}

export interface Conversation {
  id: string;
  domain: 'TUTORING' | 'CAREER';
  orderId: string | null;
  status: ConversationStatus;
  providerConversationId: string | null;
  members: ConversationMember[];
  messages: MessageReference[];
  createdAt: Date;
  updatedAt: Date;
}

export interface CreateConversationInput {
  /**
   * Generated by the application: the transport needs the platform id before
   * the row exists, so the two never drift apart.
   */
  id: string;
  domain: 'TUTORING' | 'CAREER';
  /** Assigned by the gateway, never by a client. */
  providerConversationId: string;
  members: ConversationMember[];
}

export interface ConversationPage {
  items: Conversation[];
  total: number;
}
