import { Inject, Injectable } from '@nestjs/common';

import { PrismaService } from '../../../infrastructure/prisma/prisma.service';
import type {
  Conversation,
  ConversationMemberRole,
  ConversationPage,
  ConversationStatus,
  CreateConversationInput,
  MessageModerationStatus,
  MessageType,
} from '../domain/conversation.model';
import type { ConversationRepository } from '../domain/conversation.repository';

/** Prisma adapter for {@link ConversationRepository}. */
@Injectable()
export class PrismaConversationRepository implements ConversationRepository {
  constructor(@Inject(PrismaService) private readonly prisma: PrismaService) {}

  async create(input: CreateConversationInput): Promise<Conversation> {
    // Conversation and membership in one transaction: a conversation can never
    // exist without the two counterparties.
    return this.prisma.runInTransaction(async (tx) => {
      const row = await tx.conversation.create({
        data: {
          // Generated by the application: the transport was given this id.
          id: input.id,
          domain: input.domain,
          providerConversationId: input.providerConversationId,
          // A new conversation is always open: blocking/closing are commands.
          status: 'OPEN',
          members: {
            create: input.members.map((member) => ({
              userId: member.userId,
              role: member.role,
            })),
          },
        },
      });

      const created = await tx.conversation.findUniqueOrThrow({
        where: { id: row.id },
        include: MEMBERS_AND_REFS,
      });
      return mapConversation(created);
    });
  }

  async findById(id: string): Promise<Conversation | null> {
    const row = await this.prisma.conversation.findUnique({
      where: { id },
      include: MEMBERS_AND_REFS,
    });
    return row ? mapConversation(row) : null;
  }

  async listByUser(
    userId: string,
    options: { page: number; pageSize: number },
  ): Promise<ConversationPage> {
    const where = { members: { some: { userId } } };

    const [total, rows] = await Promise.all([
      this.prisma.conversation.count({ where }),
      this.prisma.conversation.findMany({
        where,
        include: MEMBERS_AND_REFS,
        orderBy: { updatedAt: 'desc' },
        skip: (options.page - 1) * options.pageSize,
        take: options.pageSize,
      }),
    ]);

    return { items: rows.map(mapConversation), total };
  }

  async setStatus(id: string, status: ConversationStatus): Promise<Conversation> {
    const row = await this.prisma.conversation.update({
      where: { id },
      data: { status },
      include: MEMBERS_AND_REFS,
    });
    return mapConversation(row);
  }

  async listBetweenUsers(firstUserId: string, secondUserId: string): Promise<Conversation[]> {
    // Both must be members, and nobody else: V1 conversations are a pair.
    const rows = await this.prisma.conversation.findMany({
      where: {
        AND: [
          { members: { some: { userId: firstUserId } } },
          { members: { some: { userId: secondUserId } } },
        ],
      },
      include: MEMBERS_AND_REFS,
    });
    return rows.map(mapConversation);
  }
}

const MEMBERS_AND_REFS = {
  members: { orderBy: { userId: 'asc' } },
  messageRefs: { orderBy: { createdAt: 'asc' } },
} as const;

type ConversationRow = {
  id: string;
  domain: Conversation['domain'];
  orderId: string | null;
  status: ConversationStatus;
  providerConversationId: string | null;
  createdAt: Date;
  updatedAt: Date;
  members: { userId: string; role: ConversationMemberRole }[];
  messageRefs: {
    id: string;
    conversationId: string;
    externalMessageId: string;
    senderUserId: string;
    messageType: MessageType;
    moderationStatus: MessageModerationStatus;
    createdAt: Date;
  }[];
};

function mapConversation(row: ConversationRow): Conversation {
  return {
    id: row.id,
    domain: row.domain,
    orderId: row.orderId,
    status: row.status,
    providerConversationId: row.providerConversationId,
    members: row.members.map((member) => ({ userId: member.userId, role: member.role })),
    messages: row.messageRefs.map((reference) => ({
      id: reference.id,
      conversationId: reference.conversationId,
      externalMessageId: reference.externalMessageId,
      senderUserId: reference.senderUserId,
      messageType: reference.messageType,
      moderationStatus: reference.moderationStatus,
      createdAt: reference.createdAt,
    })),
    createdAt: row.createdAt,
    updatedAt: row.updatedAt,
  };
}
